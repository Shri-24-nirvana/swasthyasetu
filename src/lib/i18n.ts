export function translate(lang: Language, key: string, fallback?: string): string {
  const selectedDict = dict[lang] || dict[Language.ENGLISH];
  if (selectedDict && selectedDict[key]) {
    return selectedDict[key];
  }
  if (dict[Language.ENGLISH] && dict[Language.ENGLISH][key]) {
    return dict[Language.ENGLISH][key];
  }
  return fallback || key;
}

